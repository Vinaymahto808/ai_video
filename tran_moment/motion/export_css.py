"""Export the learned gesture tracks (avatar_widget/src/motion-data.js) as CSS keyframes for the embed card.

The card (human_bot/web/embed.html) animates its `.gest` layer with hand-written @keyframes (gNod, gTilt...).
This writes human_bot/web/learned_gestures.css with one animation per learned gesture, built from the
footage-fitted curves, and the `.gest.g-*` rules that override the hand-written ones:

    pitch (deg, chin down > 0)  -> translateY(pitch * 1.6 px) + rotateX-like squeeze is skipped (flat image)
    roll  (deg)                 -> rotate(roll deg)
    dx / dy (% of frame)        -> translateX / translateY (%)
    zoom  (delta)               -> scale(1 + zoom)

Variants (name__v2 ...) become extra classes; the card picks one at random per gesture.

    python tran_moment/motion/export_css.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "avatar_widget" / "src" / "motion-data.js"
OUT = ROOT / "human_bot" / "web" / "learned_gestures.css"
PX_PER_DEG = 1.6
# card class per gesture name (see GESTURE_CLASS / STATE_CLASS in embed.html)
CLASS = {"small_nod": "g-nod", "nod": "g-nod", "slow_nod": "g-slow", "tilt_head": "g-tilt", "open_palm": "g-open",
         "both_hands": "g-lean", "lean_in": "g-lean", "look_up": "g-lookup", "head_wobble": "g-wobble", "greeting": "g-greet"}


def load_tracks() -> dict:
    text = SRC.read_text(encoding="utf-8")
    m = re.search(r"export const LEARNED_GESTURES = Object\.freeze\((\{.*?\})\);", text, re.S)
    if not m:
        raise SystemExit("LEARNED_GESTURES not found in motion-data.js")
    body = m.group(1)
    body = re.sub(r"(\w+):", r'"\1":', body)          # bare keys -> JSON keys
    body = re.sub(r",\s*}", "}", body)
    return json.loads(body)


def sample(track: list, p: float) -> float:
    if not track:
        return 0.0
    a, b = track[0], track[-1]
    for i in range(1, len(track)):
        if p <= track[i][0]:
            a, b = track[i - 1], track[i]
            break
    span = (b[0] - a[0]) or 1.0
    k = min(1.0, max(0.0, (p - a[0]) / span))
    k = k * k * (3 - 2 * k)
    return a[1] + (b[1] - a[1]) * k


def main() -> int:
    g = load_tracks()
    css = ["/* GENERATED by tran_moment/motion/export_css.py from avatar_widget/src/motion-data.js: gesture",
           "   curves learned from footage of this face. Loaded after the hand-written keyframes in embed.html,",
           "   so these override them. Do not edit by hand. */"]
    steps = 12
    rules: dict[str, list[str]] = {}
    for name, tr in g.items():
        dur = int(tr.get("dur", 0))
        if dur < 150 or not any(k in tr for k in ("pitch", "roll", "dx", "dy", "zoom")):
            continue
        base = name.split("__v")[0]
        cls = CLASS.get(base)
        if not cls:
            continue
        anim = "l_" + name.replace("__", "_")
        frames = []
        for i in range(steps + 1):
            p = i / steps
            pitch = sample(tr.get("pitch", []), p); roll = sample(tr.get("roll", []), p)
            dx = sample(tr.get("dx", []), p); dy = sample(tr.get("dy", []), p); zoom = sample(tr.get("zoom", []), p)
            ty = dy + pitch * PX_PER_DEG / 8.52  # px of a 852-tall frame expressed in %
            frames.append(f"  {p * 100:.1f}% {{ transform: translate({dx:.2f}%, {ty:.2f}%) rotate({roll:.2f}deg) scale({1 + zoom:.4f}); }}")
        css.append(f"@keyframes {anim} {{\n" + "\n".join(frames) + "\n}")
        rules.setdefault(cls, []).append((anim, dur))
    for cls, variants in rules.items():
        anim, dur = variants[0]
        css.append(f".gest.{cls} {{ animation: {anim} {dur}ms linear 1 both; }}")
        for i, (anim_v, dur_v) in enumerate(variants[1:], start=2):
            css.append(f".gest.{cls}.v{i} {{ animation-name: {anim_v}; animation-duration: {dur_v}ms; }}")
    OUT.write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(len(v) for v in rules.values())} animations for {len(rules)} classes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
