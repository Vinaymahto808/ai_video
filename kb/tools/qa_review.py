"""Review sheet for the humans who own the facts: rows in the same category whose answers disagree
(free vs chargeable, haan vs nahi, different timings/prices) and rows the LLM could not voice.
Writes kb/seed/QA_REVIEW.md. Nothing here changes the index; it is the list to settle with ACR."""
import csv, json, re
from collections import defaultdict
from pathlib import Path

SEED = Path(__file__).resolve().parents[1] / "seed"
rows = list(csv.DictReader((SEED / "acr_customer_qa.clean.csv").open(encoding="utf-8")))
rw = json.loads((SEED / "qa_rewrites.json").read_text(encoding="utf-8")) if (SEED / "qa_rewrites.json").exists() else {}
POLAR = [("free|complimentary|muft|no charge|koi charge nahi", "chargeable|charge (lagta|hota|lagega|applicable)|paid|extra charge"),
         (r"\bhaan\b|\byes\b|ho jata|ho jayega|milti hai|available", r"\bnahi\b|\bno\b|nahi hota|nahi hai|not available|nahi milti")]
TOPICS = {"pickup": r"pick ?up|drop|doorstep", "timing": r"timing|baje|open|khul", "towing": r"tow", "warranty": r"warranty|guarantee", "emi": r"\bemi\b|installment", "sunday": r"sunday", "cashless": r"cashless"}
by_topic = defaultdict(list)
for r in rows:
    blob = (r["question"] + " " + r["answer"]).lower()
    for t, rx in TOPICS.items():
        if re.search(rx, blob): by_topic[t].append(r)
out = ["# Customer-call Q&A: what the team must settle", "", "Generated by kb/tools/qa_review.py from acr_customer_qa.clean.csv. The knowledge base carries every row below as said on the calls; Neha quotes them. Where two calls disagree, decide the official answer and edit the CSV, then rerun ingest.", ""]
conf = 0
for t, rs in by_topic.items():
    pos = [r for r in rs if re.search(POLAR[0][0], r["answer"].lower())]; neg = [r for r in rs if re.search(POLAR[0][1], r["answer"].lower())]
    yes = [r for r in rs if re.search(POLAR[1][0], r["answer"].lower())]; no = [r for r in rs if re.search(POLAR[1][1], r["answer"].lower())]
    pairs = [("free vs chargeable", pos, neg)] if pos and neg else []
    if yes and no and t in ("pickup", "towing", "emi", "sunday", "cashless"): pairs.append(("yes vs no", yes, no))
    for label, a, b in pairs:
        conf += 1
        out += [f"## {t}: {label}", ""]
        for r in a[:4]: out.append(f"- SAYS A ({r['times_seen']}x) {r['id']}: {r['answer'][:160]}")
        for r in b[:4]: out.append(f"- SAYS B ({r['times_seen']}x) {r['id']}: {r['answer'][:160]}")
        out.append("")
prices = [r for r in rows if r["has_price"] == "1"]
out += [f"## Prices quoted on calls ({len(prices)} rows)", "", "Kept as approximate; Neha adds 'exact amount gaadi dekh ke confirm hoga'. Delete a row or edit the number if a quote is wrong.", ""]
for r in prices[:60]: out.append(f"- {r['id']}: {r['answer'][:140]}")
unvoiced = [r for r in rows if r["needs_voice"] == "1" and not (rw.get(r["id"]) or {}).get("text")]
out += ["", f"## Still in third person ({len(unvoiced)} rows, the LLM rewrite was rejected or pending)", ""]
for r in unvoiced[:80]: out.append(f"- {r['id']}: {r['answer'][:140]}")
(SEED / "QA_REVIEW.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"conflict groups={conf} prices={len(prices)} unvoiced={len(unvoiced)} -> {SEED / 'QA_REVIEW.md'}")
